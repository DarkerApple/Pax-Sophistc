// bays and reefs are absent, and no border on this map should be read as a
// claim about a real one.
//
// A landmass may declare `holes`: inland seas and great lakes, which are cut
// out of it. Without them the Caspian is Kazakh steppe and Lake Superior is
// Ontario, and the countries around them get handed territory that is water.

